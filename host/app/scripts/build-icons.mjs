// Picks the built-in key icons from Tabler Icons (MIT) and writes src/lib/icons.generated.ts.
// Run after changing the list: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";

const nodes = JSON.parse(readFileSync(new URL("../node_modules/@tabler/icons/tabler-nodes-outline.json", import.meta.url), "utf8"));

const names = `
microphone microphone-off volume volume-2 volume-3 volume-off headphones music
player-play player-pause player-stop player-skip-forward player-skip-back player-record
player-track-next player-track-prev repeat arrows-shuffle
video video-off camera camera-off broadcast broadcast-off screen-share screen-share-off
device-desktop device-laptop device-tv device-mobile device-tablet device-gamepad-2
keyboard mouse copy clipboard cut file file-text folder folder-open world link mail message
message-circle send phone at home bulb bulb-off lamp power plug plug-off lock lock-open
sun moon temperature cloud wifi wifi-off bluetooth battery bolt flame droplet leaf
settings adjustments refresh rotate arrow-left arrow-right arrow-up arrow-down
chevron-left chevron-right chevrons-left chevrons-right check x plus minus star heart
bell bell-off clock calendar alarm hourglass code terminal terminal-2 bug git-branch
git-commit cpu database server download upload search zoom-in zoom-out photo brush palette
pencil trash eye eye-off hand-stop door coffee beer pizza trophy rocket flag target
apps layout-grid browser window app-window list checklist notes bookmark tag shopping-cart
user users user-plus robot mood-smile thumb-up thumb-down alert-triangle info-circle
help-circle question-mark ban player-eject scan qrcode share external-link logout login
`.split(/\s+/).filter(Boolean);

const missing = names.filter((n) => !nodes[n]);
if (missing.length) console.warn("not in Tabler:", missing.join(" "));
const picked = Object.fromEntries(names.filter((n) => nodes[n]).map((n) => [n, nodes[n]]));

writeFileSync(
  new URL("../src/lib/icons.generated.ts", import.meta.url),
  `// Generated by scripts/build-icons.mjs from Tabler Icons (https://tabler.io/icons), MIT License,
// Copyright (c) 2020-2024 Paweł Kuna. Do not edit by hand.
export const ICONS: Record<string, [string, Record<string, string>][]> = ${JSON.stringify(picked)};
`,
);
console.log(`${Object.keys(picked).length} icons`);
